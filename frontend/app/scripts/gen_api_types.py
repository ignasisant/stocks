"""Write `src/api.gen.ts` from the FastAPI app's own OpenAPI schema.

Run it with `npm run gen:api` (from frontend/app) after a route or a response
model changes; `tests/test_frontend_api_types.py` fails when the committed file
no longer matches what this prints. It is deliberately small: it spells the
response model of every GET route as a TypeScript type, plus a `Responses` map
from path (as the app writes it, under `/api/v1`) to that type, which is what
`shell/api.ts` infers `get()` answers from.

Not covered on purpose: request bodies and query parameters. A page names its
own, and `send()` stays untyped until a write is worth the same treatment.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "src" / "api.gen.ts"
PREFIX = "/v1"

HEADER = """\
// @generated by frontend/app/scripts/gen_api_types.py: do not edit by hand.
// Regenerate with `npm run gen:api`; tests/test_frontend_api_types.py guards it.
/* eslint-disable */
"""


# Globals a schema of the same name would hide from the rest of the file.
RESERVED = {"Record", "Array", "Date", "Map", "Set", "Promise", "Partial", "Response"}


def _name(raw: str) -> str:
    """A schema name as a TypeScript identifier ("Foo-Output" -> "FooOutput")."""
    parts = re.split(r"[^0-9A-Za-z_]+", raw)
    name = "".join(p[:1].upper() + p[1:] for p in parts if p)
    return f"Api{name}" if name in RESERVED else name


def _literal(value: object) -> str:
    return json.dumps(value, ensure_ascii=False)


_serialised = False


def _refs(node: object, found: set[str]) -> None:
    if isinstance(node, dict):
        ref = node.get("$ref")
        if isinstance(ref, str):
            found.add(ref.rsplit("/", 1)[-1])
        for value in node.values():
            _refs(value, found)
    elif isinstance(node, list):
        for value in node:
            _refs(value, found)


def _reachable(schema: dict, roots: list[dict]) -> set[str]:
    """Components a GET answer is made of, however deep."""
    components = schema.get("components", {}).get("schemas", {})
    found: set[str] = set()
    _refs(roots, found)
    todo = list(found)
    while todo:
        found_now: set[str] = set()
        _refs(components.get(todo.pop(), {}), found_now)
        todo += [n for n in found_now if n not in found]
        found |= found_now
    return found


def _ts(node: dict, indent: str = "") -> str:
    """One schema node as a TypeScript type expression."""
    if "$ref" in node:
        return _name(node["$ref"].rsplit("/", 1)[-1])
    if "const" in node:
        return _literal(node["const"])
    if "enum" in node:
        return " | ".join(_literal(v) for v in node["enum"]) or "never"
    for key, glue in (("anyOf", " | "), ("oneOf", " | "), ("allOf", " & ")):
        if key in node:
            members = [_ts(m, indent) for m in node[key]]
            return glue.join(dict.fromkeys(members)) or "unknown"
    kind = node.get("type")
    if isinstance(kind, list):
        return " | ".join(_ts({**node, "type": k}, indent) for k in kind)
    if kind in ("integer", "number"):
        return "number"
    if kind == "string":
        return "string"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "array":
        if "prefixItems" in node:
            return "[" + ", ".join(_ts(m, indent) for m in node["prefixItems"]) + "]"
        item = _ts(node.get("items", {}), indent)
        return f"({item})[]" if re.search(r"[|&]", item) else f"{item}[]"
    if kind == "object" or "properties" in node or "additionalProperties" in node:
        return _object(node, indent)
    return "unknown"


def _object(node: dict, indent: str) -> str:
    props = node.get("properties", {})
    required = set(node.get("required", []))
    if _serialised:
        # A field with a default is required in an answer: FastAPI dumps the
        # model whole (no route excludes unset fields), so it is always there.
        required |= set(props)
    inner = indent + "  "
    lines = []
    for key, value in props.items():
        optional = "" if key in required else "?"
        lines.append(f"{inner}{_literal(key)}{optional}: {_ts(value, inner)};")
    extra = node.get("additionalProperties")
    if extra not in (None, False):
        value = "unknown" if extra is True else _ts(extra, inner)
        lines.append(f"{inner}[key: string]: {value};")
    if not lines:
        return "Record<string, unknown>"
    return "{\n" + "\n".join(lines) + f"\n{indent}}}"


def render(schema: dict) -> str:
    global _serialised
    out = [HEADER]
    components = schema.get("components", {}).get("schemas", {})
    answers = {}
    for path, item in sorted(schema["paths"].items()):
        ok = (
            item.get("get", {})
            .get("responses", {})
            .get("200", {})
            .get("content", {})
            .get("application/json", {})
            .get("schema")
        )
        if ok and path.startswith(PREFIX):
            answers[path[len(PREFIX) :]] = ok
    responses = _reachable(schema, list(answers.values()))
    for raw in sorted(components, key=_name):
        _serialised = raw in responses
        out.append(f"export type {_name(raw)} = {_ts(components[raw])};\n")
    _serialised = True
    routes = [f"  {_literal(path)}: {_ts(ok, '  ')};" for path, ok in answers.items()]
    out.append("/** The 200 answer of every GET route, by path under `/api/v1`. */")
    out.append("export interface Responses {\n" + "\n".join(routes) + "\n}\n")
    return "\n".join(out)


def main() -> int:
    from stocks.api.app import app

    OUT.write_text(render(app.openapi()), encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
